static inline uint64_t mylite_embedded_startup_perf_start_ns(void)
{
  return mylite_embedded_startup_perf_stats_enabled()
             ? mylite_embedded_startup_perf_now_ns()
             : 0;
}

static inline void mylite_embedded_startup_perf_count(size_t index)
{
  if (mylite_embedded_startup_perf_stats_enabled())
    mylite_embedded_startup_perf_add(index, 1);
}

